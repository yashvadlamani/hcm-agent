"""Emergency assessment, fixed emergency wording, and the escalation log.

One place for everything safety-critical that must not be left to the model:
- which patient statements are emergencies (the instant keyword net),
- the exact words Clara says (911 or 988), and
- the record that an emergency happened, so the care team can act on it.

Escalations are recorded, not dispatched: no live care-team system is connected. Each record is
kept in memory, appended to ESCALATION_LOG_PATH when that is set (so it survives restarts), and
posted to ESCALATION_WEBHOOK_URL when that is set (for example a Teams or Slack channel).
Records hold the minimum needed to act: no names, dates of birth, phone numbers or transcripts.
"""

from __future__ import annotations

import json
import logging
import os
import threading
import urllib.request
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from secrets import token_hex
from typing import Any, Optional

from . import security  # noqa: E402

logger = logging.getLogger(__name__)

KINDS = ("medical", "mental_health")

# ---- Assessment: an instant keyword net that runs before the model's own clinical assessment ----

EMERGENCY_KEYWORDS = [
    "chest pain", "difficulty breathing", "shortness of breath",
    "severe headache", "sudden vision loss", "loss of consciousness",
    "severe bleeding", "unbearable pain",
    "call 911", "go to emergency", "go to hospital immediately"
]
MENTAL_HEALTH_KEYWORDS = [
    "suicidal", "suicide", "kill myself", "end my life", "ending my life", "want to die", "hurt myself",
    "self harm", "self-harm", "don't see the point of going on", "don't see the point in going on",
    "no reason to live", "not worth living", "better off dead", "better off without me", "can't go on",
]
# Severe distress. ("help me" is not here: "can you help me with my refills" is an ordinary request.
# The model's clinical assessment judges distress in context instead.)
DISTRESS_KEYWORDS = ["can't breathe", "cannot breathe", "i'm dying", "severe pain"]


def classify(statement: str) -> tuple[Optional[str], str]:
    """Keyword check of what the patient said. Returns (kind, description), or (None, "")."""
    text = statement.lower()
    for keyword in MENTAL_HEALTH_KEYWORDS:
        if keyword in text:
            return "mental_health", f"Mental health crisis: {keyword}"
    for keyword in EMERGENCY_KEYWORDS:
        if keyword in text:
            return "medical", f"Emergency detected: {keyword}"
    for keyword in DISTRESS_KEYWORDS:
        if keyword in text:
            return "medical", f"Patient distress: {keyword}"
    return None, ""


# ---- Wording: fixed, never generated by the model ----

_SCRIPTS = {
    "medical": ("I'm really sorry you're going through this, and I want you to get help right away. "
                "If this is a medical emergency, please hang up and call 9 1 1 now."),
    "mental_health": ("I'm really sorry you're feeling this way, and I'm glad you told me. "
                      "Please call or text 9 8 8, the Suicide and Crisis Lifeline, right now, "
                      "or call 9 1 1 if you're in immediate danger."),
}
FLAGGED_LINE = "I'm also flagging this call for your care team."


def emergency_script(kind: Optional[str], flagged: bool = True) -> str:
    """What Clara says in an emergency. The care-team line is said only when the call was flagged."""
    script = _SCRIPTS[kind if kind in KINDS else "medical"]
    return f"{script} {FLAGGED_LINE} Goodbye." if flagged else f"{script} Goodbye."


# ---- Routing: which care-team queue should see it. Choosing a queue does not transfer the call. ----

QUEUES = {"mental_health": "behavioral-health-crisis", "medical": "nurse-triage"}
DEFAULT_QUEUE = "care-management-general"


def queue_for(kind: Optional[str]) -> str:
    return QUEUES.get(kind, DEFAULT_QUEUE)


def next_business_day(today: Optional[date] = None) -> date:
    day = (today or datetime.now(timezone.utc).date()) + timedelta(days=1)
    while day.weekday() >= 5:
        day += timedelta(days=1)
    return day


# ---- The escalation log ----

class EscalationStore:
    """Records escalations in memory, in a JSON-lines file, and to a webhook, as configured."""

    def __init__(self, log_path: str = "", webhook_url: str = ""):
        self.log_path = Path(log_path) if log_path else None
        self.webhook_url = webhook_url
        self.records: list[dict[str, Any]] = []
        self._lock = threading.Lock()

    def record(self, record_type: str, *, notify: bool = False, **fields: Any) -> dict[str, Any]:
        """Save one escalation record and return it. Raises if the log file can't be written, so a
        caller never reports a flag that wasn't kept."""
        entry = {"id": f"ESC-{token_hex(4).upper()}", "type": record_type,
                 "created_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
                 **{key: value for key, value in fields.items() if value not in (None, "")}}
        entry["status"] = "notification_queued" if notify and self.webhook_url else "recorded"
        with self._lock:
            if self.log_path:
                self.log_path.parent.mkdir(parents=True, exist_ok=True)
                with self.log_path.open("a", encoding="utf-8") as log:
                    log.write(json.dumps(entry) + "\n")
            self.records.append(entry)
        logger.warning("ESCALATION %s %s (%s): %s", entry["id"], record_type, entry.get("kind", "routine"),
                       entry.get("reason", ""))
        if entry["status"] == "notification_queued":
            # In the background: a slow or failing webhook must never delay Clara's emergency message.
            threading.Thread(target=self._notify, args=(entry,), daemon=True).start()
        return entry

    def _notify(self, entry: dict[str, Any]) -> None:
        text = (f"Clara {entry['type'].replace('_', ' ')} {entry['id']}: {entry.get('kind', 'routine')}, "
                f"queue {entry.get('queue', DEFAULT_QUEUE)}, member {entry.get('member_id', 'unknown')}. "
                f"Reason: {entry.get('reason', 'not given')}.")
        request = urllib.request.Request(self.webhook_url, data=json.dumps({"text": text, "record": entry}).encode(),
                                         headers={"Content-Type": "application/json"}, method="POST")
        circuit = security.breaker("escalation_webhook")
        if not circuit.check()["allowed"]:  # the webhook keeps failing: don't hold threads on it for a while
            logger.error("Escalation %s not sent: the webhook circuit is open", entry["id"])
            return
        try:
            with urllib.request.urlopen(request, timeout=5):
                logger.info("Escalation %s sent to the webhook", entry["id"])
            circuit.success()
        except Exception as error:  # the record itself is already saved
            circuit.failure()
            logger.error("Escalation %s could not be sent to the webhook: %s", entry["id"], type(error).__name__)


_store: Optional[EscalationStore] = None


def store() -> EscalationStore:
    """The process-wide escalation log, configured from the environment on first use."""
    global _store
    if _store is None:
        _store = EscalationStore(os.environ.get("ESCALATION_LOG_PATH", "").strip(),
                                 os.environ.get("ESCALATION_WEBHOOK_URL", "").strip())
    return _store


def use_store(replacement: Optional[EscalationStore]) -> None:
    """Swap the escalation log (tests), or pass None to re-read the environment on next use."""
    global _store
    _store = replacement
